/**
 * Optional API credentials. Keep them out of version control:
 *   - local.properties: BRAPI_TOKEN=seu_token / COINGECKO_API_KEY=sua_chave
 *   - or environment variables with the same names.
 *
 * Brapi and CoinGecko both offer a free tier that works without a key for
 * development, but the free public limits are much lower.
 */
val localProperties = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) {
        file.inputStream().use { load(it) }
    }
}

fun secret(name: String): String =
    (localProperties.getProperty(name) ?: System.getenv(name) ?: "")
        .trim()
        .replace("\\", "\\\\")
        .replace("\"", "\\\"")

